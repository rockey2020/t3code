export function translateThreadsLabel(label: string, locale: Locale): string {
  if (locale !== "zh-CN") return label;
  if (Object.hasOwn(settingsThreadsMessages, label)) {
    return settingsThreadsMessages[label as keyof typeof settingsThreadsMessages];
  }
  for (const [pattern, key, parameter] of DYNAMIC_LABELS) {
    const match = pattern.exec(label);
    if (match)
      return translate(locale, settingsThreadsMessages, key, { [parameter]: match[1] ?? "" });
  }
  return label;
}

export function translateSnoozeWhen(
  preset: { readonly label: string; readonly whenLabel: string; readonly snoozedUntil: string },
  now: Date,
  locale: Locale,
): string {
  if (locale !== "zh-CN") return preset.whenLabel;
  const wake = new Date(preset.snoozedUntil);
  const labelNamesDay = !preset.label.startsWith("In ") && preset.label !== "Next week";
  if (labelNamesDay || wake.toDateString() === now.toDateString()) return preset.whenLabel;
  const originalDay = wake.toLocaleDateString(undefined, { weekday: "short" });
  const day = wake.toLocaleDateString(locale, { weekday: "short" });
  return `${day} ${preset.whenLabel.slice(originalDay.length + 1)}`;
}
