// Only for application-owned labels; user content must remain unchanged.
export function translatePullRequestLabel(label: string, locale: Locale): string {
  const key =
    label === "Open" ? "Open@@pull-request-state" : label === "Host" ? "Host@@code-hosting" : label;
  return locale === "zh-CN" && Object.hasOwn(pullRequestUiMessages, key)
    ? pullRequestUiMessages[key as keyof typeof pullRequestUiMessages]
    : label;
}

export function pullRequestTermAtStart(term: string, locale: Locale): string {
  return capitalizeTerm(translatePullRequestLabel(term, locale));
}

export function pullRequestFilterOptionLabel(
  option: { readonly label: string; readonly translateLabel?: boolean },
  locale: Locale,
): string {
  return option.translateLabel === true
    ? translatePullRequestLabel(option.label, locale)
    : option.label;
}
