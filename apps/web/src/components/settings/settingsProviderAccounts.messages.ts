export function translateProviderAccountsLabel(label: string, locale: Locale): string {
  if (locale !== "zh-CN") return label;
  if (Object.hasOwn(settingsProviderAccountsMessages, label))
    return settingsProviderAccountsMessages[label as keyof typeof settingsProviderAccountsMessages];
  if (label === "Disabled") return settingsProviderAccountsMessages["Disabled@@providerState"];
  const authenticated = /^(Not authenticated|Authenticated) · (.+)$/.exec(label);
  return authenticated
    ? translate(locale, settingsProviderAccountsMessages, "{status} · {method}", {
        status: translateProviderAccountsLabel(authenticated[1]!, locale),
        method: authenticated[2]!,
      })
    : label;
}
