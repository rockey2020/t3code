// Labels are authored where the worktree is described, so read them through one lookup that
// falls back to English for anything a host adds.
export function translateGitLabel(label: string, locale: Locale): string {
  return locale === "zh-CN" && Object.hasOwn(gitUiMessages, label)
    ? gitUiMessages[label as keyof typeof gitUiMessages]
    : label;
}
